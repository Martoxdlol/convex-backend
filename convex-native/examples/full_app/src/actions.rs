/// `#[convex::action(internal)]` flags the registration so
/// external clients get "function not found"; cron / scheduler
/// callers still reach it.
#[convex::action(internal)]
pub async fn nightly_cleanup(ctx: &mut ActionCtx<'_, Rt>) -> anyhow::Result<()> {
    ctx.log().info("nightly_cleanup running");
    // Idle in this example — a real app would purge stale data,
    // re-index, expire sessions, etc.
    Ok(())
}
